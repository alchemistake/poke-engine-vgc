#!/usr/bin/env node
// Generate src/doubles/ability_flags.rs: PS `ability.flags` (champions format)
// for every `Abilities` variant of the engine.
//
//   node fuzz/gen_ability_flags.js > src/doubles/ability_flags.rs
//
// Use these instead of hand-written ability lists (`cantsuppress`, ...).
const fs = require('fs');
const path = require('path');
const { Dex } = require(path.resolve(__dirname, '../../pokemon-showdown/dist/sim'));
const d = Dex.forFormat('gen9championsvgc2026regmc');
const FLAGS = ['breakable', 'cantsuppress', 'failroleplay', 'failskillswap', 'noentrain', 'noreceiver',
  'notrace', 'notransform'];
const src = fs.readFileSync(path.resolve(__dirname, '../src/genx/abilities.rs'), 'utf8');
const body = src.slice(src.indexOf('Abilities {') + 'Abilities {'.length);
const variants = body.slice(0, body.indexOf('}')).split(',').map((v) => v.trim()).filter((v) => /^[A-Z0-9]+$/.test(v));
const out = [];
out.push('// @generated by fuzz/gen_ability_flags.js from pokemon-showdown (champions');
out.push('// format). Do not edit: regenerate with');
out.push('//   node fuzz/gen_ability_flags.js > src/doubles/ability_flags.rs');
out.push('');
out.push('use crate::engine::abilities::Abilities;');
out.push('');
FLAGS.forEach((f, i) => out.push(`pub const ${f.toUpperCase()}: u16 = 1 << ${i};`));
out.push('');
out.push('/// PS `ability.flags` as a bit set of the constants above.');
out.push('pub fn ability_flags(a: Abilities) -> u16 {');
out.push('    match a {');
for (const v of variants) {
  const ab = d.abilities.get(v.toLowerCase());
  if (!ab.exists) continue;
  const fl = FLAGS.filter((f) => ab.flags && ab.flags[f]).map((f) => f.toUpperCase());
  if (fl.length) out.push(`        Abilities::${v} => ${fl.join(' | ')},`);
}
out.push('        _ => 0,');
out.push('    }');
out.push('}');
out.push('');
out.push('/// Whether ability `a` has PS flag `flag` (one of the constants above).');
out.push('pub fn has_flag(a: Abilities, flag: u16) -> bool {');
out.push('    ability_flags(a) & flag != 0');
out.push('}');
process.stdout.write(out.join('\n') + '\n');
