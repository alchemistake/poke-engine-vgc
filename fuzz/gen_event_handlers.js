#!/usr/bin/env node
// Generate src/doubles/event_handlers.rs: for every event callback name
// (`onAccuracy`, `onAnyAccuracy`, `onSourceModifyDamage`, ...), the PS effects
// in the fuzz pool that have that handler, with the sort keys PS
// `resolvePriority` gives them (order, priority, subOrder). The engine collects
// handlers from its state the way `findEventHandlers` does
// (`run_event_ties` in src/doubles/battle.rs) and speed-sorts them.
//
//   node fuzz/gen_event_handlers.js > src/doubles/event_handlers.rs
//
// Effects: the pool's abilities, statuses, the conditions of the pool's moves
// (volatile / side / slot / field / weather / terrain), and the generic
// conditions in data/conditions.ts.
const path = require('path');
const { Dex } = require(path.resolve(__dirname, '../../pokemon-showdown/dist/sim'));
const { buildSpeciesPool, buildItemPool } = require('./teams.js');

const d = Dex.forFormat('gen9championsvgc2026regmc');
const pool = buildSpeciesPool(d);
const moves = new Set();
const abilities = new Set();
for (const { sp, moves: ms } of pool) {
  ms.forEach((m) => moves.add(m));
  Object.values(sp.abilities).forEach((a) => abilities.add(d.abilities.get(a).id));
}
moves.add('struggle');

// [id, kind, effect]. Kind decides the default subOrder (PS resolvePriority).
const effects = [];
const seen = new Set();
const add = (id, kind, eff) => {
  const k = `${kind}:${id}`;
  if (!eff || seen.has(k)) return;
  seen.add(k);
  effects.push([id, kind, eff]);
};
for (const id of [...abilities].sort()) add(id, 'Ability', d.abilities.get(id));
// Held items: the pool's regular items and the Mega Stones its picks hold.
const items = new Set(buildItemPool(d).map((n) => d.items.get(n).id));
for (const { stone } of pool) if (stone) items.add(d.items.get(stone).id);
for (const id of [...items].sort()) add(id, 'Item', d.items.get(id));
for (const id of ['brn', 'par', 'slp', 'frz', 'psn', 'tox']) add(id, 'Status', d.conditions.get(id));
for (const id of ['confusion', 'flinch', 'trapped', 'partiallytrapped', 'lockedmove', 'twoturnmove',
  'mustrecharge', 'futuremove', 'stall', 'choicelock', 'rolloutstorage']) {
  const c = d.conditions.get(id);
  if (c.exists) add(id, id === 'futuremove' ? 'Slot' : 'Volatile', c);
}
for (const id of [...moves].sort()) {
  const m = d.moves.get(id);
  if (!m.exists) continue;
  if (m.volatileStatus) add(m.volatileStatus, 'Volatile', d.conditions.get(m.volatileStatus));
  if (m.self && m.self.volatileStatus) add(m.self.volatileStatus, 'Volatile', d.conditions.get(m.self.volatileStatus));
  for (const s of m.secondaries || []) if (s.volatileStatus) add(s.volatileStatus, 'Volatile', d.conditions.get(s.volatileStatus));
  if (!m.condition) continue;
  const c = d.conditions.get(id);
  if (m.sideCondition) add(m.sideCondition, 'Side', d.conditions.get(m.sideCondition));
  else if (m.slotCondition) add(m.slotCondition, 'Slot', d.conditions.get(m.slotCondition));
  else if (m.weather) add(m.weather, 'Weather', d.conditions.get(m.weather));
  else if (m.terrain || m.pseudoWeather) add(id, 'Field', c);
  else add(id, 'Volatile', c); // volatileStatus or added by code (dig, roost, ...)
}

const SUB = { Status: 0, Volatile: 2, Slot: 3, Side: 4, Field: 5, Weather: 5, Ability: 7, Item: 8 };
const SKIP_EVENTS = new Set(['Start', 'End', 'Restart', 'Residual', 'SideStart', 'SideEnd', 'SideRestart',
  'SideResidual', 'FieldStart', 'FieldEnd', 'FieldRestart', 'FieldResidual', 'Copy']);
const table = new Map(); // callback -> rows
for (const [id, kind, eff] of effects) {
  for (const key of Object.keys(eff)) {
    if (typeof eff[key] !== 'function' || !/^on[A-Z]/.test(key)) continue;
    const ev = key.replace(/^on(Ally|Foe|Any|Source)?/, '');
    if (SKIP_EVENTS.has(ev) || SKIP_EVENTS.has(key.slice(2))) continue;
    const order = eff[`${key}Order`] || 0;
    const priority = eff[`${key}Priority`] || 0;
    let sub = eff[`${key}SubOrder`] || 0;
    if (!sub) {
      sub = SUB[kind];
      if (kind === 'Ability' && (id === 'poisontouch' || id === 'perishbody')) sub = 6;
      if (kind === 'Ability' && id === 'stall') sub = 9;
    }
    if (!table.has(key)) table.set(key, []);
    table.get(key).push({ id, kind, order, priority, sub });
  }
}

const out = [];
out.push('// @generated by fuzz/gen_event_handlers.js from pokemon-showdown (champions');
out.push('// format, fuzz species pool). Do not edit: regenerate with');
out.push('//   node fuzz/gen_event_handlers.js > src/doubles/event_handlers.rs');
out.push('');
out.push('/// What holds a handler (PS `findEventHandlers` source), which decides where');
out.push('/// the engine looks for it and its default subOrder.');
out.push('#[derive(Debug, Clone, Copy, PartialEq, Eq)]');
out.push('pub enum HandlerKind {');
out.push('    Ability,');
out.push('    Status,');
out.push('    Volatile,');
out.push('    Slot,');
out.push('    Side,');
out.push('    Field,');
out.push('    Weather,');
out.push('    Item,');
out.push('}');
out.push('');
out.push('/// One PS event handler: the effect id and its `resolvePriority` sort keys');
out.push('/// (`order` 0 = none, i.e. PS `false`).');
out.push('#[derive(Debug, Clone, Copy)]');
out.push('pub struct EventHandler {');
out.push('    pub id: &\'static str,');
out.push('    pub kind: HandlerKind,');
out.push('    pub order: i64,');
out.push('    pub priority: i32,');
out.push('    pub sub_order: i32,');
out.push('}');
out.push('');
out.push('/// The handlers PS has for a callback name (`"onAnyAccuracy"`), or `&[]`.');
out.push('pub fn handlers(callback: &str) -> &\'static [EventHandler] {');
out.push('    use HandlerKind::*;');
out.push('    match callback {');
for (const key of [...table.keys()].sort()) {
  const rows = table.get(key).sort((a, b) => a.id.localeCompare(b.id) || a.kind.localeCompare(b.kind));
  out.push(`        "${key}" => &[`);
  for (const r of rows) {
    out.push(`            EventHandler { id: "${r.id}", kind: ${r.kind}, order: ${r.order}, priority: ${r.priority}, sub_order: ${r.sub} },`);
  }
  out.push('        ],');
}
out.push('        _ => &[],');
out.push('    }');
out.push('}');
process.stdout.write(out.join('\n') + '\n');
