#!/usr/bin/env node
// Generate src/doubles/item_data.rs: static data of every item in the
// engine's `Items` enum that the format knows (PS data/items.ts):
// Fling base power and whether it is a berry.
//
//   node fuzz/gen_item_data.js > src/doubles/item_data.rs
const fs = require('fs');
const path = require('path');
const { Dex } = require(path.resolve(__dirname, '../../pokemon-showdown/dist/sim'));
const d = Dex.forFormat('gen9championsvgc2026regmc');
const src = fs.readFileSync(path.resolve(__dirname, '../src/genx/items.rs'), 'utf8');
const i = src.indexOf('Items {');
const variants = src.slice(i + 7, src.indexOf('}', i)).split(',')
  .map((s) => s.replace(/\/\/.*$/gm, '').trim()).filter((v) => /^[A-Z0-9]+$/.test(v));
const fling = [];
const berries = [];
for (const v of variants) {
  const it = d.items.get(v.toLowerCase());
  if (!it.exists) continue;
  if (it.fling && it.fling.basePower) fling.push(`        Items::${v} => ${it.fling.basePower},`);
  if (it.isBerry) berries.push(v);
}
const out = [
  '// @generated by fuzz/gen_item_data.js from pokemon-showdown (champions format).',
  '// Do not edit: regenerate with',
  '//   node fuzz/gen_item_data.js > src/doubles/item_data.rs',
  '',
  'use crate::engine::items::Items;',
  '',
  '/// Fling base power (`item.fling.basePower`), 0 when the item cannot be flung.',
  'pub fn fling_power(item: Items) -> u8 {',
  '    match item {',
  ...fling,
  '        _ => 0,',
  '    }',
  '}',
  '',
  '/// `item.isBerry`.',
  'pub fn is_berry(item: Items) -> bool {',
  '    matches!(',
  '        item,',
  ...berries.map((v, k) => `        ${k ? '| ' : ''}Items::${v}`),
  '    )',
  '}',
  '',
];
process.stdout.write(out.join('\n'));
