#!/usr/bin/env node
// Generate src/doubles/megas.rs: which forme each Mega Stone turns its holder
// into (PS champions `canMegaEvo`: `item.megaStone[baseSpecies.name]`).
//
//   node fuzz/gen_megas.js > src/doubles/megas.rs
const fs = require('fs');
const path = require('path');
const { Dex } = require(path.resolve(__dirname, '../../pokemon-showdown/dist/sim'));
const d = Dex.forFormat('gen9championsvgc2026regmc');
const enumBody = (file, name) => {
  const src = fs.readFileSync(path.resolve(__dirname, '..', file), 'utf8');
  const i = src.indexOf(`${name} {`);
  return new Set(src.slice(i + name.length + 2, src.indexOf('}', i)).split(',').map((s) => s.replace(/\/\/.*$/gm, '').trim()).filter(Boolean));
};
const items = enumBody('src/genx/items.rs', 'Items');
const names = enumBody('src/pokemon.rs', 'PokemonName');
const abilities = enumBody('src/genx/abilities.rs', 'Abilities');
const rows = [];
for (const it of d.items.all()) {
  if (it.isNonstandard || !it.megaStone) continue;
  const item = it.id.toUpperCase();
  if (!items.has(item)) throw new Error(`Items has no ${item}`);
  for (const [base, mega] of Object.entries(it.megaStone)) {
    const b = d.species.get(base).id.toUpperCase();
    const m = d.species.get(mega).id.toUpperCase();
    if (!names.has(b) || !names.has(m)) throw new Error(`PokemonName misses ${b} or ${m}`);
    const ab = d.abilities.get(d.species.get(mega).abilities['0']).id.toUpperCase();
    if (!abilities.has(ab)) throw new Error(`Abilities has no ${ab}`);
    rows.push(`        (Items::${item}, PokemonName::${b}) => Some((PokemonName::${m}, Abilities::${ab})),`);
  }
}
rows.sort();
const out = [
  '// @generated by fuzz/gen_megas.js from pokemon-showdown (champions format).',
  '// Do not edit: regenerate with',
  '//   node fuzz/gen_megas.js > src/doubles/megas.rs',
  '',
  'use crate::engine::abilities::Abilities;',
  'use crate::engine::items::Items;',
  'use crate::pokemon::PokemonName;',
  '',
  '/// The forme `base` Mega Evolves into holding `item` (PS `item.megaStone[species]`)',
  "/// and that forme's ability (`species.abilities['0']`).",
  'pub fn mega_forme(item: Items, base: PokemonName) -> Option<(PokemonName, Abilities)> {',
  '    match (item, base) {',
  ...rows,
  '        _ => None,',
  '    }',
  '}',
  '',
  '/// A Mega Stone: its `onTakeItem` keeps it on the species it evolves (the',
  '/// only holders the format allows), so it can never be taken.',
  'pub fn is_mega_stone(item: Items) -> bool {',
  '    matches!(',
  '        item,',
  ...[...new Set(rows.map((r) => r.match(/Items::(\w+)/)[1]))].map((i, k, a) => `        ${k ? '| ' : ''}Items::${i}`),
  '    )',
  '}',
  '',
];
process.stdout.write(out.join('\n'));
