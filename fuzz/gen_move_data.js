#!/usr/bin/env node
// Generate src/doubles/move_data.rs: per-move PS data the engine's `Choice`
// table does not carry (champions dex): the raw `pp` (Mimic copies it as is)
// and the `failmimic` flag; and the species' `nfe` (Eviolite).
//
//   node fuzz/gen_move_data.js > src/doubles/move_data.rs
'use strict';
const fs = require('fs');
const path = require('path');
const { Dex } = require(path.resolve(__dirname, '../../pokemon-showdown/dist/sim'));
const d = Dex.forFormat('gen9championsvgc2026regmc');
const src = fs.readFileSync(path.resolve(__dirname, '../src/choices.rs'), 'utf8');
const i = src.indexOf('Choices {');
const variants = new Set(src.slice(i + 9, src.indexOf('}', i)).split(',')
  .map((s) => s.replace(/\/\/.*$/gm, '').trim()).filter((v) => /^[A-Z0-9]+$/.test(v)));
const pnSrc = fs.readFileSync(path.resolve(__dirname, '../src/pokemon.rs'), 'utf8');
const pj = pnSrc.indexOf('PokemonName {');
const pnames = new Set(pnSrc.slice(pj + 13, pnSrc.indexOf('}', pj)).split(',')
  .map((x) => x.replace(/\/\/.*$/gm, '').trim()).filter((v) => /^[A-Z0-9]+$/.test(v)));
const nfe = [];
const nums = [];
for (const sp of d.species.all()) {
  const v = sp.id.toUpperCase();
  if (sp.exists && sp.nfe && pnames.has(v)) nfe.push(v);
  if (sp.exists && pnames.has(v) && [483, 484, 487, 493, 649, 773, 888, 889, 1017].includes(sp.num)) {
    nums.push(`        PokemonName::${v} => ${sp.num},`);
  }
}
const pp = [];
const failMimic = [];
const mirror = [];
// Metronome `onHit`: standard (or Unobtainable) moves with the `metronome` flag, by num.
const metronome = d.moves.all()
  .filter((m) => (!m.isNonstandard || m.isNonstandard === 'Unobtainable') && m.flags.metronome)
  .sort((a, b) => a.num - b.num)
  .map((m) => m.id.toUpperCase());
for (const v of metronome) if (!variants.has(v)) throw new Error(`Choices has no ${v}`);
for (const mv of d.moves.all()) {
  const v = mv.id.toUpperCase();
  if (!variants.has(v) || !mv.exists) continue;
  pp.push(`        Choices::${v} => ${mv.pp},`);
  if (mv.flags.failmimic) failMimic.push(v);
  if (mv.flags.mirror && !mv.isZ && !mv.isMax) mirror.push(v);
}
const out = [
  '// @generated by fuzz/gen_move_data.js from pokemon-showdown (champions format).',
  '// Do not edit: regenerate with',
  '//   node fuzz/gen_move_data.js > src/doubles/move_data.rs',
  '',
  'use crate::choices::Choices;',
  'use crate::pokemon::PokemonName;',
  '',
  '/// The move\'s raw `pp` in the dex (not the champions in-battle PP).',
  'pub fn raw_pp(m: Choices) -> u8 {',
  '    match m {',
  ...pp,
  '        _ => 0,',
  '    }',
  '}',
  '',
  '/// `baseSpecies.num` of the species with a held-item lock (0 for the rest).',
  'pub fn lock_num(p: PokemonName) -> u16 {',
  '    match p {',
  ...nums,
  '        _ => 0,',
  '    }',
  '}',
  '',
  '/// `species.nfe`: it can still evolve (Eviolite).',
  'pub fn nfe(p: PokemonName) -> bool {',
  '    matches!(',
  '        p,',
  ...nfe.map((v, k) => `        ${k ? '| ' : ''}PokemonName::${v}`),
  '    )',
  '}',
  '',
  '/// The moves Metronome can call, in PS order (`num`).',
  'pub const METRONOME_MOVES: &[Choices] = &[',
  ...metronome.map((v) => `    Choices::${v},`),
  '];',
  '',
  '/// `move.flags.mirror` (Mirror Move can copy it).',
  'pub fn mirror(m: Choices) -> bool {',
  '    matches!(',
  '        m,',
  ...mirror.map((v, k) => `        ${k ? '| ' : ''}Choices::${v}`),
  '    )',
  '}',
  '',
  '/// `move.flags.failmimic`.',
  'pub fn fail_mimic(m: Choices) -> bool {',
  '    matches!(',
  '        m,',
  ...failMimic.map((v, k) => `        ${k ? '| ' : ''}Choices::${v}`),
  '    )',
  '}',
  '',
];
process.stdout.write(out.join('\n'));
